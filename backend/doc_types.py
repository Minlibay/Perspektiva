# Сколько символов начала текста смотреть: свой тип документ называет в первых строках,
# дальше идут ссылки на другие документы («по Договору №…», «Акт № 1»).
HEAD_CHARS = 800


def _squash(s: str) -> str:
    return re.sub(r"[^0-9a-zа-я]", "", (s or "").lower().replace("ё", "е"))


def _strip_service_blocks(text: str) -> str:
    """Убирает служебные заголовки экстрактора («=== КОЛОНТИТУЛ (header) ===»), оставляя
    их содержимое: в колонтитуле Акта и Плана как раз написано, что это за документ."""
    return re.sub(r"===[^=\n]{0,60}===", " ", text or "")


def classify_by_content(text: str) -> str | None:
    head = _squash(_strip_service_blocks(text)[:HEAD_CHARS])
    if not head:
        return None
    for dt in DOC_TYPES:
        if any(all(part in head for part in group) for group in dt["content"]):
            return dt["key"]
    return None


def classify_by_name(file_name: str) -> str | None:
    """names — регулярные выражения, совпадающие с НАЧАЛА слова: «акт» не должен
    находиться внутри «контракт», а «план» — внутри «Шаблон плана» должен."""
    name = (file_name or "").lower().replace("ё", "е")
    for dt in DOC_TYPES:
        if any(re.search(r"(?<![а-яa-z])" + k, name) for k in dt["names"]):
            return dt["key"]
    return None


def classify_document(file_name: str, text: str) -> str:
    """Тип документа (ключ DOC_TYPES) или 'unknown'."""
    return classify_by_content(text) or classify_by_name(file_name) or "unknown"


def classify_all(all_texts: dict) -> dict:
    """{имя файла: тип} для всех извлечённых текстов."""
    return {fn: classify_document(fn, txt) for fn, txt in all_texts.items()}


def files_of_type(doc_types: dict, *keys: str) -> list:
    return [fn for fn, t in doc_types.items() if t in keys]
